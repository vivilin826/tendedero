import AppKit

/// Hangs images copied to the clipboard, like a screenshot taken with Control
/// held or an image copied in Preview, and plain text, which is drawn as a
/// small card. Each one is saved as a PNG in Tendedero's own folder, so on
/// the line it behaves like any screenshot.
///
/// Off until the user turns it on. The pasteboard has no change notification,
/// so its change count is checked twice a second; what was copied is only read
/// once its types say it is a picture and nothing else, or just text.
@MainActor
final class ClipboardWatcher {
    private let onImage: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last image saved. Some apps put the same image on the clipboard
    /// again; it hangs once, unless it has been taken down since.
    private var last: (png: Data, url: URL)?

    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Copies that carry a picture but are not one. Text from a spreadsheet
    /// or a document also comes as an image of itself. A file copied in
    /// Finder brings its icon, and a photo copied from the line brings its
    /// file. Password managers and similar apps mark private or temporary
    /// copies, following nspasteboard.org.
    ///
    /// Plain text on its own is now hung too (as a text card), so `.string`
    /// is not ignored outright: `check()` decides by what else is there.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Anything bigger is not a screenshot.
    private static let maxBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000
    /// A text card wider than this would not fit the line's card area.
    nonisolated private static let textCardWidth: CGFloat = 320
    /// Text longer than this is truncated on the card (the full text is kept
    /// in the clipboard, and the card is the same PNG either way).
    nonisolated private static let textCardMaxChars = 500

    init(onImage: @escaping (URL) -> Void) {
        self.onImage = onImage
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }),
              pb.changeCount == count else { return }
        // An image on its own, as before.
        if let type = pb.availableType(from: [.png, .tiff]),
           let data = pb.data(forType: type), data.count <= Self.maxBytes {
            // Decoding a large image takes a moment, so it happens off the main thread.
            DispatchQueue.global(qos: .userInitiated).async { [weak self] in
                let png = ClipboardWatcher.png(from: data, type: type)
                DispatchQueue.main.async {
                    // Copied over again in the meantime: that copy is the one that counts.
                    guard let png, NSPasteboard.general.changeCount == count else { return }
                    self?.save(png)
                }
            }
            return
        }
        // Plain text on its own: draw it as a card and hang that.
        // A string plus an image is the image (spreadsheets, documents render
        // themselves); a string plus a file is the file.
        let hasImage = pb.availableType(from: [.png, .tiff]) != nil
        let hasFile = items.contains { $0.types.contains(.fileURL) }
        guard !hasImage, !hasFile,
              items.allSatisfy({ $0.types.contains(.string) || $0.types.contains(.init("org.nspasteboard.ConcealedType")) }),
              let text = pb.string(forType: .string), !text.isEmpty else { return }
        // Rendering takes a moment, so it happens off the main thread.
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let png = ClipboardWatcher.textCardPNG(text)
            DispatchQueue.main.async {
                // Copied over again in the meantime: that copy is the one that counts.
                guard let png, NSPasteboard.general.changeCount == count else { return }
                self?.save(png, text: text)
            }
        }
    }

    /// PNG bytes are kept as they are; TIFF becomes PNG. Either way the image
    /// must decode and have a sane size.
    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    /// Draws copied plain text as a small card, the way the line shows it.
    /// The card is a white rounded sheet with a tinted top edge, so a text
    /// clip reads as a note and not as a screenshot.
    nonisolated private static func textCardPNG(_ raw: String) -> Data? {
        let text = String(raw.prefix(textCardMaxChars))
        let font = NSFont.systemFont(ofSize: 17, weight: .medium)
        let inset: CGFloat = 22
        let maxWidth = textCardWidth - inset * 2
        // First pass: measure how tall the text is with wrapping.
        let attributes: [NSAttributedString.Key: Any] = [
            .font: font,
            .foregroundColor: NSColor(calibratedWhite: 0.13, alpha: 1),
        ]
        let paragraph = NSMutableParagraphStyle()
        paragraph.lineSpacing = 3
        paragraph.lineBreakMode = .byWordWrapping
        var attrs = attributes
        attrs[.paragraphStyle] = paragraph
        let measured = (text as NSString).boundingRect(
            with: CGSize(width: maxWidth, height: .greatestFiniteMagnitude),
            options: [.usesLineFragmentOrigin, .usesFontLeading],
            attributes: attrs)
        let textHeight = ceil(measured.height)
        let scale: CGFloat = 2 // Retina-sharp.
        let width = Int(textCardWidth * scale)
        let height = Int((textHeight + inset * 2 + 14) * scale)
        guard let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .calibratedRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        rep.size = NSSize(width: CGFloat(width) / scale, height: CGFloat(height) / scale)
        NSGraphicsContext.saveGraphicsState()
        guard let ctx = NSGraphicsContext(bitmapImageRep: rep) else {
            NSGraphicsContext.restoreGraphicsState()
            return nil
        }
        NSGraphicsContext.current = ctx
        // Card: white rounded sheet, a thin gray border and a soft tinted
        // header strip, matching the line's glass cards well enough.
        let bounds = CGRect(x: 0, y: 0, width: CGFloat(width) / scale, height: CGFloat(height) / scale)
        let path = NSBezierPath(roundedRect: bounds, xRadius: 16, yRadius: 16)
        NSColor(calibratedWhite: 0.98, alpha: 1).setFill()
        path.fill()
        path.lineWidth = 1
        NSColor(calibratedWhite: 0.82, alpha: 1).setStroke()
        path.stroke()
        let header = NSBezierPath(roundedRect: CGRect(x: 0, y: bounds.height - 46, width: bounds.width, height: 46),
                                  xRadius: 16, yRadius: 16)
        NSColor(calibratedRed: 0.85, green: 0.90, blue: 0.98, alpha: 0.85).setFill()
        header.fill()
        // Text, wrapped and truncated with an ellipsis when it does not fit.
        let textRect = CGRect(x: inset, y: inset + 14, width: maxWidth, height: textHeight)
        let drawText = text as NSString
        let full = NSMutableAttributedString(string: text, attributes: attrs)
        full.addAttribute(.paragraphStyle, value: paragraph, range: NSRange(location: 0, length: full.length))
        full.draw(in: textRect)
        _ = drawText
        ctx.flushGraphics()
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }

    /// Saves a copied image, and for a text card the original text next to it
    /// in a same-named `.txt` file. Copying the card from the line then pastes
    /// the text itself, not a picture of it.
    private func save(_ png: Data, text: String? = nil) {
        if let last, last.png == png, FileManager.default.fileExists(atPath: last.url.path) { return }
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()).png")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()) \(n).png")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            try png.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            if let text {
                let textURL = url.deletingPathExtension().appendingPathExtension("txt")
                try text.write(to: textURL, atomically: true, encoding: .utf8)
                try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: textURL.path)
            }
            last = (png, url)
            onImage(url)
        } catch {
            try? fm.removeItem(at: url)
            try? fm.removeItem(at: url.deletingPathExtension().appendingPathExtension("txt"))
            log.error("Could not save a copied image: \(error.localizedDescription, privacy: .public)")
        }
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
